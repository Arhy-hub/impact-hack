"""Build pitch/index.html: every slide in pitch/slides/ as one page you can present in a browser.

    python pitch/build.py

The slide files are the source (they come from the Claude Slides deck, see
pitch/README.md). This turns them into plain HTML: the live house animation
(<x-embed>) becomes an iframe, icons (<x-icon>) become simple symbols, and
speaker notes (<aside>) are hidden. Arrow keys / click step through each
slide's reveals, then the next slide. Press N to show the speaker notes.
"""

from __future__ import annotations

import html
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent

ICONS = {"Activity": "∿", "Chart": "▤", "Clock": "◷", "Lightning": "ϟ", "Home": "⌂",
         "Key": "⚿", "Globe": "◍", "Users": "☺", "Chat": "✎", "Database": "▦", "Settings": "⚙"}


def convert(section: str) -> str:
    def embed(m: re.Match) -> str:
        return f'<iframe style="{m.group(1)};border:0" srcdoc="{html.escape(m.group(2), quote=True)}"></iframe>'
    section = re.sub(r'<x-embed style="([^"]*)">(.*?)</x-embed>', embed, section, flags=re.S)
    section = re.sub(r'<x-icon name="(\w+)"([^>]*)></x-icon>',
                     lambda m: f'<span{m.group(2)} data-icon>{ICONS.get(m.group(1), "•")}</span>', section)
    return section


def main() -> None:
    deck = json.loads((HERE / "deck.json").read_text(encoding="utf-8"))
    css = (HERE / "deck.css").read_text(encoding="utf-8")
    fonts = "".join(f'<link rel="stylesheet" href="{f["href"]}">' for f in deck["faces"].values() if "href" in f)
    slides = "\n".join(convert((HERE / "slides" / f"{sid}.html").read_text(encoding="utf-8")) for sid in deck["order"])
    page = f"""<!doctype html>
<!-- Generated by pitch/build.py from pitch/slides/. Edit the slides, then rebuild. -->
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>{html.escape(deck["title"])}</title>{fonts}
<style>
html,body{{margin:0;height:100%;background:#0E0D14;overflow:hidden}}
#stage{{position:absolute;left:50%;top:50%;width:1920px;height:1080px;transform-origin:0 0}}
#stage>section{{position:absolute;inset:0;width:1920px;height:1080px;display:none!important}}
#stage>section.on{{display:flex!important}}
section aside{{display:none}}
body.notes section.on aside{{display:block;position:absolute;left:0;right:0;bottom:0;background:#000c;color:#fff;font:28px/1.4 Inter,sans-serif;padding:24px 128px}}
[data-icon]{{display:flex;align-items:center;justify-content:center;font-size:48px;line-height:1}}
.fragment:not(.visible):not(.opt-dim):not(.opt-win){{opacity:0}}
#count{{position:fixed;right:16px;bottom:12px;font:14px Inter,sans-serif;color:#8F8A9C}}
{css}
</style></head><body>
<div id="stage">
{slides}
</div>
<div id="count"></div>
<script>
const S=[...document.querySelectorAll('#stage>section')];let i=0,f=0;
const steps=s=>{{const fr=[...s.querySelectorAll('.fragment')];const ix=[...new Set(fr.map((e,k)=>e.dataset.fragmentIndex??('z'+k)))];return ix.map(x=>fr.filter((e,k)=>(e.dataset.fragmentIndex??('z'+k))===x))}};
function show(){{S.forEach((s,k)=>s.classList.toggle('on',k===i));const st=steps(S[i]);st.flat().forEach(e=>e.classList.remove('visible'));st.slice(0,f).flat().forEach(e=>e.classList.add('visible'));
document.getElementById('count').textContent=(i+1)+' / '+S.length;location.hash='slide-'+(i+1)}}
function go(d){{const n=steps(S[i]).length;if(d>0){{if(f<n)f++;else if(i<S.length-1){{i++;f=0}}}}else{{if(f>0)f--;else if(i>0){{i--;f=steps(S[i]).length}}}}show()}}
function fit(){{const k=Math.min(innerWidth/1920,innerHeight/1080);document.getElementById('stage').style.transform=`scale(${{k}}) translate(-50%,-50%)`}}
addEventListener('keydown',e=>{{if(['ArrowRight','ArrowDown',' ','PageDown'].includes(e.key))go(1);else if(['ArrowLeft','ArrowUp','PageUp'].includes(e.key))go(-1);else if(e.key==='n'||e.key==='N')document.body.classList.toggle('notes')}});
addEventListener('click',e=>{{if(!e.target.closest('a'))go(e.clientX<innerWidth/3?-1:1)}});
function fromHash(){{const m=location.hash.match(/slide-(\\d+)/);const n=m?Math.max(0,Math.min(S.length-1,m[1]-1)):0;if(n!==i){{i=n;f=0}}}}
addEventListener('hashchange',()=>{{fromHash();show()}});
addEventListener('resize',fit);fromHash();fit();show();
</script></body></html>
"""
    (HERE / "index.html").write_text(page, encoding="utf-8")
    print(f"Wrote {HERE / 'index.html'} ({len(deck['order'])} slides)")


if __name__ == "__main__":
    main()
